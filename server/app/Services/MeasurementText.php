<?php

namespace App\Services;

class MeasurementText
{
    public function format(array $r): string
    {
        if ($r['status'] === 'success') return '❤️ Новый замер по запросу: '.$r['bpm']." уд/мин\nИзмерен: "
            .app(DashboardText::class)->time($r['measured_at_ms']);
        return match ($r['status']) {
            'queued' => 'Запрос создан. Ожидаем телефон и новый замер; экран часов включать не нужно.',
            'dispatched', 'measuring' => 'Телефон получил запрос. Ожидаем новый замер с часов…',
            'off_body' => 'Часы сняты: замер не выполнен.',
            'wearing_unknown' => 'Ношение неизвестно: замер не выполнен. Дождитесь статуса «На руке».',
            'monitoring_stopped' => 'Мониторинг на часах выключен. Включите его в приложении часов.',
            'phone_unavailable' => 'Телефон не получил запрос за 20 секунд. Проверьте передачу, Wi-Fi и доступность сервера.',
            'phone_restarted' => 'Телефон перезапустился: запрос отменён. Нажмите «Измерить сейчас» ещё раз.',
            'no_connection', 'send_failed' => 'Нет связи телефона с часами. Новый замер не получен.',
            'multiple_watches' => 'К телефону подключено несколько часов. Оставьте нужные часы.',
            'busy' => 'На телефоне или часах уже выполняется другой замер. Повторите позже.',
            'cooldown', 'duplicate_request' => 'Слишком частый повтор. Подождите 10 секунд.',
            'permission_lost' => 'Нет разрешения на измерение пульса в фоне. Проверьте разрешения часов.',
            'unsupported' => 'Разовый замер не поддерживается часами.',
            'sensor_error' => 'Датчик не смог выполнить новый замер. Повторите позже.',
            'invalid_result', 'clock_unavailable' => 'Не удалось проверить свежесть замера. Проверьте время устройств.',
            'cancelled' => 'Запрос отменён. Новый замер не выполнен.',
            default => 'Новый замер не получен за время ожидания. Проверьте связь и посадку часов.',
        };
    }
}
